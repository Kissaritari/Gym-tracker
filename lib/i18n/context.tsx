"use client"

import { createContext, useCallback, useContext, useEffect, useMemo, useState, type ReactNode } from "react"
import { localeTag, translate, type Locale } from "./messages"

const LanguageContext = createContext({ locale: "en" as Locale, setLocale: (_locale: Locale) => {} })
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>("en")
  useEffect(() => {
    try {
      const stored = localStorage.getItem("form-one-language")
      if (stored === "fi" || stored === "en") updateLocale(stored)
    } catch { /* The selector still works when storage is disabled. */ }
  }, [])
  useEffect(() => {
    document.documentElement.lang = locale
    document.title = locale === "fi" ? "FORM / ONE — Fiksumpaa harjoittelua" : "FORM / ONE — Training intelligence"
    const clear = (event: Event) => {
      if (event.target instanceof HTMLInputElement || event.target instanceof HTMLTextAreaElement || event.target instanceof HTMLSelectElement) event.target.setCustomValidity("")
    }
    const invalid = (event: Event) => {
      const input = event.target
      if (!(input instanceof HTMLInputElement || input instanceof HTMLTextAreaElement || input instanceof HTMLSelectElement)) return
      input.setCustomValidity("")
      const validity = input.validity
      let message = "Check this value."
      if (validity.valueMissing) message = "Please fill out this field."
      else if (validity.typeMismatch) message = "Enter a valid email address."
      else if (validity.tooShort) message = "This value is too short."
      else if (validity.tooLong) message = "This value is too long."
      else if (validity.rangeUnderflow || validity.rangeOverflow) message = "Enter a value within the allowed range."
      else if (validity.badInput || validity.stepMismatch) message = "Enter a valid number."
      input.setCustomValidity(translate(locale, message))
    }
    document.querySelectorAll("input, textarea, select").forEach((input) => (input as HTMLInputElement).setCustomValidity(""))
    document.addEventListener("invalid", invalid, true)
    document.addEventListener("input", clear, true)
    document.addEventListener("change", clear, true)
    return () => {
      document.removeEventListener("invalid", invalid, true)
      document.removeEventListener("input", clear, true)
      document.removeEventListener("change", clear, true)
    }
  }, [locale])
  const setLocale = useCallback((value: Locale) => {
    updateLocale(value)
    try { localStorage.setItem("form-one-language", value) } catch { /* Session-only preference. */ }
  }, [])
  const context = useMemo(() => ({ locale, setLocale }), [locale, setLocale])
  return <LanguageContext.Provider value={context}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  const { locale, setLocale } = useContext(LanguageContext)
  const t = useCallback((message: string, values?: Record<string, string | number>) => translate(locale, message, values), [locale])
  return { locale, setLocale, t, languageTag: localeTag(locale) }
}

// Also works inside server-rendered pages: this client boundary subscribes to
// the shared language, so switching languages never reloads an active workout.
export function T({ children, text, values }: { children?: ReactNode; text?: string; values?: Record<string, string | number> }) {
  const { t } = useI18n()
  const value = text ?? children
  return <>{typeof value === "string" ? t(value, values) : value}</>
}

export function LanguageSelector() {
  const { locale, setLocale } = useI18n()
  return <div className="relative z-40 flex justify-end border-b border-border bg-background px-4 py-2">
    <label className="flex items-center gap-2 text-sm">
      <span>{locale === "fi" ? "Kieli" : "Language"}</span>
      <select className="rounded-md border border-border bg-card px-3 py-2 text-foreground" value={locale} onChange={(event) => setLocale(event.target.value === "fi" ? "fi" : "en")}>
        <option value="en" lang="en">English</option><option value="fi" lang="fi">Suomi</option>
      </select>
    </label>
  </div>
}

export function LocalDate({ value, dateOnly = false }: { value: string; dateOnly?: boolean }) {
  const { languageTag } = useI18n()
  return <>{new Intl.DateTimeFormat(languageTag, dateOnly ? { dateStyle: "medium" } : { dateStyle: "medium", timeStyle: "short" }).format(new Date(value))}</>
}

export function LocalNumber({ value }: { value: number }) {
  const { languageTag } = useI18n()
  return <>{new Intl.NumberFormat(languageTag).format(value)}</>
}

export function SessionNote({ value }: { value: string }) {
  const { t } = useI18n()
  // These exact formats are generated by the app and also identify workout days.
  // Keep the stored values stable; translate only their presentation.
  let match = /^Day (\d+): Completed (\d+)\/(\d+) exercises$/.exec(value)
  if (match) return <>{t("Day {day}: Completed {done}/{total} exercises", { day: match[1], done: match[2], total: match[3] })}</>
  match = /^Day (\d+)$/.exec(value)
  if (match) return <>{t("Day {day}", { day: match[1] })}</>
  match = /^Completed (\d+)\/(\d+) exercises$/.exec(value)
  if (match) return <>{t("Completed {done}/{total} exercises", { done: match[1], total: match[2] })}</>
  match = /^Completed (\d+) sets$/.exec(value)
  if (match) return <>{t("Completed {count} sets", { count: match[1] })}</>
  return <>{value}</>
}
